def test_same_file_under_one_label_is_counted_once(folders):
    real, fake = folders
    first = write_image(real / "a.png", 1)
    (real / "copy.png").write_bytes(first.read_bytes())
    write_image(fake / "b.png", 2)
    dataset = build_dataset(real, fake, MediaConfig())
    assert len(dataset.items) == 2
    assert dataset.duplicates_removed == 1


def test_same_file_under_both_labels_is_excluded_and_reported(folders):
    real, fake = folders
    shared = write_image(real / "a.png", 1)
    fake.mkdir()
    (fake / "a.png").write_bytes(shared.read_bytes())
    write_image(fake / "b.png", 2)
    dataset = build_dataset(real, fake, MediaConfig())
    assert [item.label for item in dataset.items] == ["fake"]
    assert dataset.label_conflicts == 1


def test_copies_with_one_perceptual_hash_always_share_a_split(folders):
    real, fake = folders
    original = write_image(real / "a.png", 1)
    info = PngImagePlugin.PngInfo()
    info.add_text("note", "same pixels, different bytes")
    Image.open(original).save(fake / "a.png" if fake.mkdir() else fake / "a.png", pnginfo=info)
    for seed in range(20):
        dataset = build_dataset(real, fake, MediaConfig(), seed=seed)
        assert len(dataset.items) == 2
        assert dataset.items[0].split == dataset.items[1].split


def test_split_is_repeatable_and_changes_with_the_seed(folders):
    real, fake = folders
    for number in range(40):
        write_image(real / f"{number}.png", number)
    fake.mkdir()
    splits = [
        [item.split for item in build_dataset(real, fake, MediaConfig(), seed=seed).items] for seed in (1, 1, 2)
    ]
    assert splits[0] == splits[1]
    assert splits[0] != splits[2]
    assert {"calibration", "test"} == set(splits[0])


def test_subfolders_become_categories(folders):
    real, fake = folders
    write_image(real / "a.png", 1)
    write_image(fake / "Face Swap!" / "deep" / "b.png", 2)
    categories = {item.label: item.category for item in build_dataset(real, fake, MediaConfig()).items}
    assert categories == {"real": "uncategorized", "fake": "face_swap"}


def test_other_files_and_broken_images_are_counted_not_hidden(folders):
    real, fake = folders
    write_image(real / "a.png", 1)
