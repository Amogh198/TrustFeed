def test_models_are_compared_on_the_same_images(folders):
    real, fake = folders
    write_image(real / "a.png", 1)
    write_image(fake / "b.png", 2)
    seen = []

    def factory(config):
        seen.append((config.model_id, config.model_revision))
        return ByImageId({1: 0.1, 2: 0.9} if config.model_id == "one/model" else {1: 0.9, 2: 0.1}, model_id=config.model_id)

    models = [("one/model", PINNED), ("two/model", PINNED)]
    result = run(folders, {}, factory=factory, models=models)
    assert seen == models
    first, second = result["models"]
    assert first["model_revision"] == PINNED
    assert first["current_bands"]["all_images"]["auc"] == 1.0
    assert second["current_bands"]["all_images"]["auc"] == 0.0


def test_results_never_contain_file_or_folder_paths(tmp_path):
    real = tmp_path / "PRIVATEROOT" / "real"
    fake = tmp_path / "PRIVATEROOT" / "fake"
    write_image(real / "persons_name.png", 1)
    write_image(fake / "another_name.png", 2)
    out = tmp_path / "out.json"
