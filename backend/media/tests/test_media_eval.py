SOURCE = {"name": "test images", "licence": "generated by this test", "url": ""}
PINNED = "a" * 40


class ByImageId:
    """Scores an image by the id painted into its corner, so scores can be set after splitting."""

    model_revision = "test-revision"

    def __init__(self, scores: dict[int, float], *, broken: set[int] | None = None, model_id="test/model") -> None:
        self.model_id = model_id
        self.scores = scores
        self.broken = broken or set()

    def predict(self, images):
        ids = [read_id(image) for image in images]
        if self.broken & set(ids):
            raise ClassifierUnavailable("This image could not be scored.")
        return [self.scores[item] for item in ids]


def read_id(image) -> int:
    red, green, _ = image.convert("RGB").getpixel((4, 4))
    return red * 256 + green


def write_image(path: Path, image_id: int, *, size: int = 256) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    image = patterned_image(seed=image_id + 1, size=size)
    image.paste((image_id // 256, image_id % 256, 0), (0, 0, 16, 16))
    image.save(path, format="PNG")
    return path


@pytest.fixture
def folders(tmp_path):
    return tmp_path / "real", tmp_path / "fake"


def run(folders, scores, **kwargs):
    real, fake = folders
    factory = kwargs.pop("factory", lambda config: ByImageId(scores))
    return run_benchmark(real, fake, sources=[SOURCE], classifier_factory=factory, **kwargs)


# Statistics


@pytest.mark.parametrize(
    ("successes", "total", "expected"),
    [
        (8, 10, (0.4902, 0.9433)),
        (0, 10, (0.0, 0.2775)),
        (10, 10, (0.7225, 1.0)),
        (1, 2, (0.0945, 0.9055)),
        (50, 100, (0.4038, 0.5962)),
    ],
)
def test_wilson_interval_matches_hand_calculation(successes, total, expected):
    assert wilson_interval(successes, total) == pytest.approx(expected, abs=0.0002)


def test_no_data_gives_no_rate_rather_than_zero():
    assert wilson_interval(0, 0) is None
    assert proportion(0, 0) == {"count": 0, "total": 0, "value": None, "ci95": None}


def test_histogram_bin_edges():
    assert histogram([0.0, 0.0999, 0.1, 0.5, 0.9999, 1.0]) == [2, 1, 0, 0, 0, 1, 0, 0, 0, 2]


@pytest.mark.parametrize(
    ("fakes", "reals", "expected"),
    [
        ([0.9, 0.8], [0.1, 0.2], 1.0),
        ([0.1, 0.2], [0.9, 0.8], 0.0),
        ([0.5, 0.5], [0.5, 0.5], 0.5),
        ([0.2, 0.8], [0.2, 0.6], 0.625),
        ([0.5, 0.5, 0.7], [0.5, 0.6], 0.5),
    ],
)
def test_auc_with_ties(fakes, reals, expected):
    items = [Scored("fake", s, "low") for s in fakes] + [Scored("real", s, "low") for s in reals]
    assert auc(items) == pytest.approx(expected, abs=0.0001)


def test_auc_needs_both_classes():
    assert auc([Scored("fake", 0.5, "low")]) is None


def test_inconclusive_counts_against_recall_and_is_reported():
    items = [
        Scored("fake", 0.9, "elevated"),
        Scored("fake", 0.5, "inconclusive"),
        Scored("fake", 0.1, "low"),
        Scored("real", 0.9, "elevated"),
        Scored("real", 0.1, "low"),
    ]
    result = evaluate(items)
    assert result["confusion"] == {
        "fake": {"elevated": 1, "inconclusive": 1, "low": 1},
        "real": {"elevated": 1, "inconclusive": 0, "low": 1},
    }
    assert result["recall"]["value"] == pytest.approx(0.3333, abs=0.0001)
    assert result["false_positive_rate"]["value"] == 0.5
    assert result["inconclusive_rate"]["count"] == 1
    assert result["inconclusive_rate"]["total"] == 5
    assert result["too_few_to_conclude"] is True


def test_large_enough_samples_are_not_flagged():
    items = [Scored("fake", 0.9, "elevated")] * 30 + [Scored("real", 0.1, "low")] * 30
    assert evaluate(items)["too_few_to_conclude"] is False
    assert evaluate(items[:59])["too_few_to_conclude"] is True


def test_threshold_separates_classes():
    items = [Scored("fake", 0.8 + i / 100, "elevated") for i in range(10)]
    items += [Scored("real", 0.1 + i / 100, "low") for i in range(10)]
    cut, reason = choose_threshold(items)
    assert cut == pytest.approx(0.8)
    assert reason is None
    measured = at_threshold(items, cut)
    assert measured["recall"]["value"] == 1.0
    assert measured["false_positive_rate"]["value"] == 0.0


def test_threshold_tie_prefers_fewer_false_alarms():
    items = [Scored("fake", 0.9, "elevated")] * 10 + [Scored("real", 0.1, "low")] * 9 + [Scored("real", 0.2, "low")]
    assert choose_threshold(items)[0] == 0.9


def test_threshold_refuses_too_little_data():
    cut, reason = choose_threshold([Scored("fake", 0.9, "elevated")] * 9 + [Scored("real", 0.1, "low")] * 50)
    assert cut is None
    assert "has 9 fake and 50 real" in reason


