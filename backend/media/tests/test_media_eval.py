# Whole runs


def seeded_set(folders, count=30):
    """Write images, then return the ids in each split so scores can differ by split."""
    real, fake = folders
    for number in range(count):
        write_image(real / f"{number}.png", number)
        write_image(fake / f"{number}.png", 1000 + number)
    dataset = build_dataset(real, fake, MediaConfig())
    by_group = {"real": {"calibration": [], "test": []}, "fake": {"calibration": [], "test": []}}
    for item in dataset.items:
        by_group[item.label][item.split].append(int(item.path.stem) + (1000 if item.label == "fake" else 0))
    return by_group


def test_threshold_comes_only_from_calibration_and_is_measured_on_test(folders):
    groups = seeded_set(folders)
    scores = {}
    # On calibration the classes separate at 0.6. On test the model is exactly backwards.
    scores.update({i: 0.6 for i in groups["fake"]["calibration"]})
    scores.update({i: 0.2 for i in groups["real"]["calibration"]})
    scores.update({i: 0.1 for i in groups["fake"]["test"]})
    scores.update({i: 0.95 for i in groups["real"]["test"]})
    model = run(folders, scores)["models"][0]
    best = model["best_threshold"]
    assert best["value"] == 0.6
    assert best["chosen_on"] == "calibration split"
    assert best["calibration_n"] == len(groups["fake"]["calibration"]) + len(groups["real"]["calibration"])
    assert best["test_split"]["recall"]["value"] == 0.0
    assert best["test_split"]["false_positive_rate"]["value"] == 1.0
    assert best["test_split"]["n"]["fake"] == len(groups["fake"]["test"])


def test_result_has_all_requested_measures(folders):
    real, fake = folders
    write_image(real / "plain" / "a.png", 1)
    write_image(real / "recompressed" / "b.png", 2)
    write_image(fake / "face_swap" / "c.png", 3)
    write_image(fake / "ai_generated" / "d.png", 4)
    write_image(fake / "ai_generated" / "e.png", 5)
    result = run(folders, {1: 0.1, 2: 0.9, 3: 0.1, 4: 0.9, 5: 0.5})
    assert result["schema"] == "media-eval-1"
    assert result["sources"] == [SOURCE]
    assert result["dataset"]["real"] == 2
    assert result["dataset"]["fake"] == 3
    assert result["dataset"]["by_category"]["fake/ai_generated"] == 2
    model = result["models"][0]
    assert model["status"] == "complete"
    everything = model["current_bands"]["all_images"]
    assert everything["confusion"]["fake"] == {"elevated": 1, "inconclusive": 1, "low": 1}
    assert everything["recall"]["ci95"] is not None
    assert everything["false_positive_rate"]["count"] == 1
    assert everything["too_few_to_conclude"] is True
    assert sum(everything["score_histogram"]["fake"]) == 3
    assert model["by_category"]["ai_generated"]["recall"]["value"] == 0.5
    assert model["by_category"]["face_swap"]["recall"]["value"] == 0.0
    assert model["by_category"]["recompressed"]["false_positive_rate"]["value"] == 1.0
    assert model["by_category"]["recompressed"]["recall"]["value"] is None
    assert model["best_threshold"]["value"] is None
    assert "calibration split" in model["best_threshold"]["not_chosen_because"]


