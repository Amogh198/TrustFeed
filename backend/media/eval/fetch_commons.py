"""Download a labelled benchmark set from Wikimedia Commons, checking each file's stated licence.

    python -m backend.media.eval.fetch_commons --out C:/Projects/samples/commons --per-category 150

Images go to --out, which must be outside the repository. A manifest of each file's page,
licence and author goes beside them, so a result can be traced. Commons categories are
human-curated, so a label can be wrong. Real photos are limited to uploads from before 2020,
when photorealistic generators were rare, which lowers that risk but does not remove it.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import random
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from collections.abc import Callable, Iterable, Sequence
from dataclasses import asdict, dataclass
from pathlib import Path

API = "https://commons.wikimedia.org/w/api.php"
USER_AGENT = "TrustFeed-benchmark/0.1 (hackathon research; https://github.com/Amogh198/TrustFeed)"
THUMBNAIL_WIDTH = 1024
# Commons serves scaled thumbnails from thumb and files already small enough from upload.
# Accepting only upload would select mostly small images, which skews the set by image size.
_ALLOWED_HOSTS = {"upload.wikimedia.org", "thumb.wikimedia.org"}
_ALLOWED_LICENCE = re.compile(r"^(cc0|public domain|pd\b|pd-|cc[ -]by(-sa)?[ -]\d)", re.IGNORECASE)
_REFUSED_LICENCE = re.compile(r"\b(nc|nd|non-?commercial|no derivatives|fair use)\b", re.IGNORECASE)
_MIMES = {"image/jpeg", "image/png", "image/webp"}
_REPO = Path(__file__).resolve().parents[3]
_MAX_TITLES_PER_REQUEST = 50
# Longer title lists are refused with HTTP 414, and Commons titles can be very long.
_MAX_TITLES_LENGTH = 4000

Fetch = Callable[[str], bytes]


@dataclass(frozen=True)
class Plan:
    label: str
    category: str
    roots: tuple[str, ...]
    uploaded_before: str | None = None


PLANS = (
    Plan("fake", "ai_generated", ("AI-generated images", "Images generated by Stable Diffusion", "AI-generated photographs")),
    Plan("fake", "edited", ("Photomontages",)),
    Plan(
        "real",
        "people",
        ("Portrait photographs", "Quality images of people", "Portrait photographs of women", "Portrait photographs of men"),
        "2020-01-01",
    ),
    Plan(
        "real",
        "general",
        ("Featured pictures of landscapes", "Featured pictures of animals", "Featured pictures of architecture"),
        "2020-01-01",
    ),
)


def licence_allowed(short_name: str | None) -> bool:
    """Accept public domain, CC0, CC BY and CC BY-SA. Anything unclear is refused."""
    if not short_name:
        return False
    name = short_name.strip()
    return bool(_ALLOWED_LICENCE.match(name)) and not _REFUSED_LICENCE.search(name)


def _plain(text: object) -> str:
    """Author fields hold HTML from the file page. Keep only its text."""
    cleaned = re.sub(r"<[^>]+>", " ", str(text or ""))
    return " ".join(html.unescape(cleaned).split())[:200]


def http_fetch(url: str, retries: int = 4) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310 - https only, see callers
                return response.read(30 * 1024 * 1024)
        except urllib.error.HTTPError as exc:
            if exc.code not in {429, 500, 502, 503, 504} or attempt == retries - 1:
                raise
            time.sleep(2 ** (attempt + 1))
    raise OSError("Commons could not be reached.")


def _api(fetch: Fetch, **params) -> dict:
    query = urllib.parse.urlencode({"action": "query", "format": "json", **params})
    return json.loads(fetch(f"{API}?{query}"))


def list_files(fetch: Fetch, roots: Iterable[str], *, limit: int, max_depth: int = 2) -> list[str]:
    """Walk categories breadth first, and return file titles without repeats."""
    queue = [(root, 0) for root in roots]
    seen_categories = set()
    titles: dict[str, None] = {}
    while queue and len(titles) < limit:
        name, depth = queue.pop(0)
        if name in seen_categories:
            continue
        seen_categories.add(name)
        token = None
        while len(titles) < limit:
            params = {"list": "categorymembers", "cmtitle": f"Category:{name}", "cmlimit": 500, "cmtype": "file|subcat"}
            if token:
                params["cmcontinue"] = token
            data = _api(fetch, **params)
            for member in data.get("query", {}).get("categorymembers", []):
                title = member.get("title", "")
                if title.startswith("File:"):
                    titles[title] = None
                elif title.startswith("Category:") and depth < max_depth:
                    queue.append((title.removeprefix("Category:"), depth + 1))
            token = data.get("continue", {}).get("cmcontinue")
            if not token:
                break
    return list(titles)[:limit]


def _title_batches(titles: Sequence[str]) -> Iterable[list[str]]:
    """Split titles so that no request's URL grows too long once encoded."""
    batch: list[str] = []
    length = 0
    for title in titles:
        cost = len(urllib.parse.quote_plus(title + "|"))
        if batch and (len(batch) == _MAX_TITLES_PER_REQUEST or length + cost > _MAX_TITLES_LENGTH):
            yield batch
            batch, length = [], 0
        batch.append(title)
        length += cost
    if batch:
        yield batch


def describe_files(fetch: Fetch, titles: Sequence[str]) -> list[dict]:
    described = []
    for batch in _title_batches(titles):
        data = _api(
            fetch,
            titles="|".join(batch),
            prop="imageinfo",
            iiprop="url|mime|timestamp|extmetadata",
            iiurlwidth=THUMBNAIL_WIDTH,
            iiextmetadatafilter="LicenseShortName|Artist",
        )
        for page in data.get("query", {}).get("pages", {}).values():
            info = (page.get("imageinfo") or [None])[0]
            if info:
                described.append({"title": page.get("title", ""), **info})
    return described


def usable(info: dict, plan: Plan) -> bool:
    metadata = info.get("extmetadata") or {}
    licence = (metadata.get("LicenseShortName") or {}).get("value")
    if not licence_allowed(licence) or info.get("mime") not in _MIMES:
        return False
    if plan.uploaded_before and not str(info.get("timestamp", "9999")) < plan.uploaded_before:
        return False
    # A real-photo category can still hold generated images, so names are checked too.
    if plan.label == "real" and re.search(r"\b(ai[- ]generated|stable diffusion|midjourney|dall)", info["title"], re.I):
        return False
    url = urllib.parse.urlsplit(info.get("thumburl") or "")
    return url.scheme == "https" and url.hostname in _ALLOWED_HOSTS


def _file_name(title: str, url: str) -> str:
    suffix = Path(urllib.parse.urlsplit(url).path).suffix.lower() or ".jpg"
    # Hashed, because Commons titles often name the person in the photo.
    return hashlib.sha256(title.encode()).hexdigest()[:24] + suffix


def fetch_plan(plan: Plan, out: Path, per_category: int, fetch: Fetch, seed: int, delay_s: float) -> list[dict]:
    titles = list_files(fetch, plan.roots, limit=per_category * 12)
    candidates = [info for info in describe_files(fetch, titles) if usable(info, plan)]
    random.Random(f"{seed}:{plan.category}").shuffle(candidates)
    folder = out / plan.label / plan.category
    folder.mkdir(parents=True, exist_ok=True)
    kept = []
    for info in candidates:
        if len(kept) >= per_category:
            break
        target = folder / _file_name(info["title"], info["thumburl"])
        try:
            if not target.exists():
                target.write_bytes(fetch(info["thumburl"]))
                time.sleep(delay_s)
        except OSError:
            continue
        metadata = info["extmetadata"]
        kept.append(
            {
                "file": str(target.relative_to(out)).replace("\\", "/"),
                "label": plan.label,
                "category": plan.category,
                "page": info.get("descriptionurl"),
                "licence": metadata["LicenseShortName"]["value"],
                "author": _plain((metadata.get("Artist") or {}).get("value")),
                "uploaded": info.get("timestamp"),
            }
        )
    return kept


def main(argv: list[str] | None = None, fetch: Fetch = http_fetch) -> int:
    parser = argparse.ArgumentParser(prog="python -m backend.media.eval.fetch_commons", description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="folder for images, outside the repository")
    parser.add_argument("--per-category", type=int, default=150)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--delay", type=float, default=0.2, help="seconds between downloads, to be polite")
    args = parser.parse_args(argv)
    if args.out.resolve().is_relative_to(_REPO):
        print("error: images must stay outside the repository.", file=sys.stderr)
        return 2

    records: list[dict] = []
    for plan in PLANS:
        kept = fetch_plan(plan, args.out, args.per_category, fetch, args.seed, args.delay)
        print(f"{plan.label}/{plan.category}: {len(kept)} images")
        records.extend(kept)
        # Written after each category, so a later failure can't lose the record of these files.
        manifest = {
            "source": "Wikimedia Commons",
            "url": "https://commons.wikimedia.org/",
            "plans": [asdict(item) for item in PLANS],
            "seed": args.seed,
            "files": records,
        }
        (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return 0 if records else 1


if __name__ == "__main__":
    sys.exit(main())
